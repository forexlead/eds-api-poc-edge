#!/usr/bin/env node
/*
 * Sandbox programs do not support Edge Function secret stores, so the TMDB token is
 * baked into the Wasm at build time instead. This reads `.env` (gitignored) and writes
 * `src/generated/secrets.js` (also gitignored). Must run before every serve/build/deploy.
 *
 * Never print the token: failures report the key name only.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENV_FILE = resolve(ROOT, '.env');
const OUT_FILE = resolve(ROOT, 'src/generated/secrets.js');
const REQUIRED = ['TMDB_TOKEN'];

function die(message) {
  console.error(`\ngen-secrets: ${message}\n`);
  process.exit(1);
}

function parseEnv(text) {
  const vars = {};
  for (const rawLine of text.split('\n')) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (/^(".*"|'.*')$/s.test(value)) value = value.slice(1, -1);
    vars[key] = value;
  }
  return vars;
}

let env;
try {
  env = parseEnv(readFileSync(ENV_FILE, 'utf8'));
} catch (err) {
  if (err.code === 'ENOENT') {
    die(`.env not found at ${ENV_FILE}\n  Create it with: ${REQUIRED.map((k) => `${k}=<value>`).join('\n                  ')}`);
  }
  die(`could not read .env: ${err.message}`);
}

const missing = REQUIRED.filter((key) => !env[key]);
if (missing.length > 0) {
  die(`missing or empty in .env: ${missing.join(', ')}`);
}

const body = REQUIRED.map((key) => `export const ${key} = ${JSON.stringify(env[key])};\n`).join('');
mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(
  OUT_FILE,
  `// GENERATED by scripts/gen-secrets.mjs — do not edit, do not commit.\n${body}`,
  'utf8'
);

console.log(`gen-secrets: wrote src/generated/secrets.js (${REQUIRED.join(', ')})`);
